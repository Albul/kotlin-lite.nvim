local defs = require("kotlin-lite.defs")

describe("defs.signature", function()
    it("strips visibility + expect", function()
        assert.are.same({ "inline fun AutoCloseable(crossinline a: () -> Unit): AutoCloseable", "expect" },
            { defs._signature("public expect inline fun AutoCloseable(crossinline a: () -> Unit): AutoCloseable {") })
    end)
    it("strips actual + the trailing brace", function()
        assert.are.same({ "class Foo", "actual" }, { defs._signature("actual class Foo {") })
    end)
    it("annotations first: actual still seen", function()
        assert.are.same({ "typealias Exception = java.lang.Exception", "actual" },
            { defs._signature('@SinceKotlin("1.1") public actual typealias Exception = java.lang.Exception') })
        assert.are.same({ "class Foo", "actual" }, { defs._signature("@JvmInline @Suppress(\"X\") actual class Foo {") })
    end)
    it("keeps data, no expect/actual", function()
        assert.are.same({ "data class Point(val x: Int)" }, { defs._signature("data class Point(val x: Int)") })
    end)
end)

describe("defs.source_set", function()
    it("commonMain -> common", function()
        assert.are.equal("common", defs._source_set("m/src/commonMain/kotlin/A.kt"))
    end)
    it("in a jar path", function()
        assert.are.equal("jvm", defs._source_set("jvmMain/jdk7/kotlin/A.kt"))
    end)
    it("jvmTest kept", function()
        assert.are.equal("jvmTest", defs._source_set("m/src/jvmTest/kotlin/A.kt"))
    end)
    it("plain src/main -> nil", function()
        assert.is_nil(defs._source_set("src/main/kotlin/A.kt"))
    end)
end)
