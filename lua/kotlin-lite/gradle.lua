-- Accessors gradle generates: BuildConfig.X -> the build files,
-- libs.x.y -> the version catalog, projects.x -> the module.

local search = require("kotlin-lite.search")
local scope = require("kotlin-lite.scope")

local M = { kind = "generated by gradle", home = "the build files" }

local BUILD_FILES = { "**/build.gradle.kts", "**/build.gradle" }
local SETTINGS_FILES = { "**/settings.gradle.kts", "**/settings.gradle" }
local CATALOG = "libs.versions.toml"

-- BuildConfig fields of the android plugin, by the property they come from
local BUILT_IN = {
    VERSION_NAME = "versionName",
    VERSION_CODE = "versionCode",
    APPLICATION_ID = "applicationId",
    BUILD_TYPE = "buildTypes",
    FLAVOR = "productFlavors",
}

local CATALOG_SECTIONS = { plugins = true, versions = true, bundles = true }

-- the segments after the receiver: libs.plugins.kotlin.jvm with the cursor
-- on `kotlin` -> { "plugins", "kotlin", "jvm" }; a call (`.get()`) ends it
local function accessor_path(ctx)
    local path = vim.list_slice(ctx.recv.segs, 2)
    path[#path + 1] = ctx.word
    local line, i = ctx.sc.mask[ctx.lnum], ctx.e + 1
    while true do
        local seg, j = line:match("^%.([%a_][%w_]*)()", i)
        if not seg or line:match("^%s*[({]", j) then return path end
        path[#path + 1] = seg
        i = j
    end
end

--- `ctx` on a generated accessor -> { what, label, name, ... }, else nil
function M.ref(ctx)
    local r = ctx.code and not ctx.call and ctx.recv
    if not r or r.kind ~= "chain" or r.ctor then return nil end
    local class = r.segs[#r.segs]
    if class == "BuildConfig" or class == "BuildKonfig" then
        return { what = "field", class = class, name = ctx.word, label = class .. "." .. ctx.word }
    end
    local root = r.segs[1]
    if root ~= "libs" and root ~= "projects" then return nil end
    local path = accessor_path(ctx)
    return {
        what = root == "libs" and "catalog" or "project",
        path = path,
        name = path[#path],
        label = root .. "." .. table.concat(path, "."),
    }
end

local function rg_in(E, globs, re)
    local args = { "-e", re }
    for _, g in ipairs(globs) do vim.list_extend(args, { "-g", g }) end
    return E.run(args, { search.root() })
end

local function result(items, label, rows, home)
    local res = { label = label, listing = { title = label, rows = rows }, home = home }
    if #items == 1 then
        res.jump = items[1]
    else
        for _, it in ipairs(items) do it.rank = 0 end
        res.pool, res.word = items, label
    end
    return res
end

-------------------------------------------------------------------
-- BuildConfig
-------------------------------------------------------------------

-- name of the block a hit is in: debug, release, defaultConfig, ...
local function block_of(it, scans)
    scans[it.filename] = scans[it.filename] or scope.scan(vim.fn.readfile(it.filename))
    local b = scope.innermost(scans[it.filename], scope.key(it.lnum, it.col - 1))
    return b.callee or vim.fs.basename(it.filename)
end

local function field(ref, E)
    local prop = BUILT_IN[ref.name]
    local re = prop and ("\\b" .. prop .. "\\b") or ([=[buildConfigField\b.*["']]=] .. ref.name .. [=[["']]=])
    local items = rg_in(E, BUILD_FILES, re)
    if #items == 0 then return nil end
    local scans, rows = {}, {}
    for _, it in ipairs(items) do rows[#rows + 1] = { block_of(it, scans), it.text } end
    return result(items, ref.label, rows)
end

-------------------------------------------------------------------
-- version catalog
-------------------------------------------------------------------

local function section_at(lines, lnum)
    for l = lnum, 1, -1 do
        local s = lines[l]:match("^%s*%[([%w-]+)%]")
        if s then return s end
    end
end

-- `name = ...` of the [versions] section
local function version_line(lines, name)
    for l, line in ipairs(lines) do
        if line:match("^%s*" .. vim.pesc(name) .. "%s*=") and section_at(lines, l) == "versions" then
            return vim.trim(line)
        end
    end
end

local function catalog(ref, E)
    local section, key = "libraries", ref.path
    if CATALOG_SECTIONS[key[1]] and #key > 1 then section, key = key[1], vim.list_slice(key, 2) end
    local re = "^\\s*" .. table.concat(key, "[-_.]") .. "\\s*="
    local items, rows, files = {}, {}, {}
    for _, it in ipairs(rg_in(E, { "**/" .. CATALOG }, re)) do
        files[it.filename] = files[it.filename] or vim.fn.readfile(it.filename)
        local lines = files[it.filename]
        if section_at(lines, it.lnum) == section then
            items[#items + 1] = it
            rows[#rows + 1] = { "[" .. section .. "]", it.text }
            local v = it.text:match('version%.ref%s*=%s*"([^"]+)"')
            local vline = v and version_line(lines, v)
            if vline then rows[#rows + 1] = { "[versions]", vline } end
        end
    end
    if #items == 0 then return nil end
    return result(items, ref.label, rows, CATALOG)
end

-------------------------------------------------------------------
-- type-safe project accessors
-------------------------------------------------------------------

-- ":core-ui" and projects.coreUi compare as "coreui"
local function module_key(path)
    return (path:gsub("^:", ""):gsub("[-_]", ""):lower())
end

local function project(ref, E)
    local want = module_key(table.concat(ref.path, ":"))
    local loose = table.concat(vim.tbl_map(function(seg)
        return (seg:gsub("%u", "[-_]?%0"))
    end, ref.path), ":")
    for _, it in ipairs(rg_in(E, SETTINGS_FILES, [=[(?i)["']:?]=] .. loose .. [=[["']]=])) do
        for path in it.text:gmatch([=[["'](:?[%w_.:-]+)["']]=]) do
            if module_key(path) == want then
                local dir = vim.fs.dirname(it.filename) .. "/" .. path:gsub("^:", ""):gsub(":", "/")
                local target = it
                for _, f in ipairs({ "build.gradle.kts", "build.gradle" }) do
                    local file = dir .. "/" .. f
                    if vim.fn.filereadable(file) == 1 then
                        target = { filename = file, lnum = 1, col = 1, text = vim.fn.readfile(file, "", 1)[1] or "" }
                        break
                    end
                end
                return result({ target }, ref.label, { { path, vim.fn.fnamemodify(dir, ":.") } }, "settings.gradle")
            end
        end
    end
end

function M.resolve(ref, E)
    if ref.what == "field" then return field(ref, E) end
    if ref.what == "catalog" then return catalog(ref, E) end
    return project(ref, E)
end

--- gu: the accessor in Kotlin / Java / build scripts
function M.usages(ref, E)
    local re = "\\b" .. ref.label:gsub("%.", "\\.") .. "\\b"
    local items = E.run({ "-e", re }, { search.root() })
    for _, it in ipairs(items) do search.at_word(it, ref.name) end
    return items
end

return M
