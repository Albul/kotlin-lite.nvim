-- Classes gradle generates: BuildConfig fields lead to the build files.

local search = require("kotlin-lite.search")
local scope = require("kotlin-lite.scope")

local M = { kind = "generated by gradle", home = "the build files" }

local BUILD_FILES = { "**/build.gradle.kts", "**/build.gradle" }

-- BuildConfig fields of the android plugin, by the property they come from
local BUILT_IN = {
    VERSION_NAME = "versionName",
    VERSION_CODE = "versionCode",
    APPLICATION_ID = "applicationId",
    BUILD_TYPE = "buildTypes",
    FLAVOR = "productFlavors",
}

--- `ctx` on X of BuildConfig.X -> { class, name }, else nil
function M.ref(ctx)
    local r = ctx.code and not ctx.call and ctx.recv
    if not r or r.kind ~= "chain" or r.ctor then return nil end
    local class = r.segs[#r.segs]
    if class ~= "BuildConfig" and class ~= "BuildKonfig" then return nil end
    return { class = class, name = ctx.word }
end

local function rg_in(E, globs, re)
    local args = { "-e", re }
    for _, g in ipairs(globs) do vim.list_extend(args, { "-g", g }) end
    return E.run(args, { search.root() })
end

-- name of the block a hit is in: debug, release, defaultConfig, ...
local function block_of(it, scans)
    scans[it.filename] = scans[it.filename] or scope.scan(vim.fn.readfile(it.filename))
    local b = scope.innermost(scans[it.filename], scope.key(it.lnum, it.col - 1))
    return b.callee or vim.fs.basename(it.filename)
end

local function result(items, label)
    local scans, rows = {}, {}
    for _, it in ipairs(items) do rows[#rows + 1] = { block_of(it, scans), it.text } end
    local res = { label = label, listing = { title = label, rows = rows } }
    if #items == 1 then
        res.jump = items[1]
    else
        for _, it in ipairs(items) do it.rank = 0 end
        res.pool, res.word = items, label
    end
    return res
end

function M.resolve(ref, E)
    local prop = BUILT_IN[ref.name]
    local re = prop and ("\\b" .. prop .. "\\b") or ([=[buildConfigField\b.*["']]=] .. ref.name .. [=[["']]=])
    local items = rg_in(E, BUILD_FILES, re)
    if #items == 0 then return nil end
    return result(items, ref.class .. "." .. ref.name)
end

--- gu: BuildConfig.X in Kotlin / Java
function M.usages(ref, E)
    local items = E.run({ "-e", ("\\b%s\\.%s\\b"):format(ref.class, ref.name) }, { search.root() })
    for _, it in ipairs(items) do search.at_word(it, ref.name) end
    return items
end

return M
